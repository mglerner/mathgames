// @ts-check
// Globs one-file-per-thing sources into the three generated registries
// (DESIGN.md section 11, "No shared append points"):
//   src/gen/<zone>/*.js     -> src/gen/registry.generated.js    (default export: Generator)
//   src/misc/malrules/*.js  -> src/misc/malrules.generated.js   (default export: MalRule)
//   src/app/mounts/*.js     -> src/app/mounts.generated.js      (named export: mount(app))
// Works on an empty tree (writes empty registries). Output is sorted, so it is
// deterministic, and a file is rewritten only when its content changes
// (atomically, via rename) so concurrent readers never see a partial file.
// Run: node scripts/gen-registry.js [root]

import { readdirSync, readFileSync, writeFileSync, renameSync, mkdirSync, existsSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HEADER = '// GENERATED by scripts/gen-registry.js -- do not edit, do not commit.\n';

/**
 * @param {string} dir
 * @returns {string[]} sorted .js file names directly in dir (no dotfiles, no *.generated.js)
 */
function jsFiles(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && e.name.endsWith('.js') && !e.name.startsWith('.') && !e.name.endsWith('.generated.js'))
    .map((e) => e.name)
    .sort();
}

/**
 * @param {string} dir
 * @returns {string[]} sorted subdirectory names (no dotdirs)
 */
function subdirs(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isDirectory() && !e.name.startsWith('.'))
    .map((e) => e.name)
    .sort();
}

/** @param {string} p @param {string} content @returns {boolean} true if written */
function writeIfChanged(p, content) {
  if (existsSync(p) && readFileSync(p, 'utf8') === content) return false;
  mkdirSync(dirname(p), { recursive: true });
  const tmp = `${p}.${process.pid}.tmp`;
  writeFileSync(tmp, content);
  renameSync(tmp, p);
  return true;
}

/**
 * A registry module whose items are each file's default export, plus the file list.
 * @param {string[]} rel import paths relative to the registry file
 * @param {string} name exported array name
 * @param {string} kind for the error message
 */
function defaultRegistry(rel, name, kind) {
  let s = HEADER;
  rel.forEach((r, i) => { s += `import * as m${i} from ${JSON.stringify(r)};\n`; });
  s += `\nexport const ${name}Files = ${JSON.stringify(rel, null, 2)};\n`;
  s += `\n/** @param {any} ns @param {number} i */\n`;
  s += `function pick(ns, i) {\n`;
  s += `  if (!('default' in ns)) throw new Error(${JSON.stringify(kind)} + ' file ' + ${name}Files[i] + ' has no default export');\n`;
  s += `  return ns.default;\n}\n`;
  s += `\nexport const ${name} = [${rel.map((_, i) => `m${i}`).join(', ')}].map(pick);\n`;
  return s;
}

/**
 * @param {string} [root] repo root (default: this script's parent dir)
 * @returns {{ generators: string[]; malrules: string[]; mounts: string[]; written: string[] }}
 */
export function genRegistry(root = resolve(dirname(fileURLToPath(import.meta.url)), '..')) {
  const genDir = join(root, 'src', 'gen');
  const generators = subdirs(genDir).flatMap((z) => jsFiles(join(genDir, z)).map((f) => `./${z}/${f}`));
  const malrules = jsFiles(join(root, 'src', 'misc', 'malrules')).map((f) => `./malrules/${f}`);
  const mounts = jsFiles(join(root, 'src', 'app', 'mounts')).map((f) => `./mounts/${f}`);

  let mountSrc = HEADER;
  mounts.forEach((r, i) => { mountSrc += `import { mount as m${i} } from ${JSON.stringify(r)};\n`; });
  mountSrc += `\nexport const mountFiles = ${JSON.stringify(mounts, null, 2)};\n`;
  mountSrc += `\n/** @type {((app: any) => unknown)[]} */\nexport const mounts = [${mounts.map((_, i) => `m${i}`).join(', ')}];\n`;

  /** @type {[string, string][]} */
  const outputs = [
    [join(genDir, 'registry.generated.js'), defaultRegistry(generators, 'generators', 'generator')],
    [join(root, 'src', 'misc', 'malrules.generated.js'), defaultRegistry(malrules, 'malrules', 'mal-rule')],
    [join(root, 'src', 'app', 'mounts.generated.js'), mountSrc],
  ];
  const written = outputs.filter(([p, c]) => writeIfChanged(p, c)).map(([p]) => p);
  return { generators, malrules, mounts, written };
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = genRegistry(process.argv[2] ? resolve(process.argv[2]) : undefined);
  console.log(`gen-registry: ${r.generators.length} generators, ${r.malrules.length} mal-rules, ${r.mounts.length} mounts` +
    (r.written.length ? ` (wrote ${r.written.length} file(s))` : ' (unchanged)'));
}
